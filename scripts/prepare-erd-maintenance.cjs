const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const stage = path.resolve(__dirname, '../tmp/pdfs/erd-update/Documentation');
const destination = path.join(stage, 'integrations/erd');
fs.mkdirSync(destination, { recursive: true });
let build = fs.readFileSync(path.join(__dirname, 'build-connected-erd.cjs'), 'utf8');
build = build.replace("path.resolve(__dirname, '..', 'tmp/pdfs/erd-update/Documentation')", "path.resolve(__dirname, '../..')");
assert(!build.includes('tmp/pdfs/erd-update/Documentation'));
fs.writeFileSync(path.join(destination, 'build-connected.cjs'), build);
let check = fs.readFileSync(path.join(__dirname, 'check-connected-erd.cjs'), 'utf8');
check = check.replace("path.resolve(__dirname,'../tmp/pdfs/erd-update/Documentation')", "path.resolve(__dirname,'../..')");
check = check.replace("path.resolve(__dirname,'../../Documentation/Docs.html')", "path.join(root,'Docs.html')");
check = check.replace("path.resolve(__dirname,'../tmp/pdfs/erd-update/rendered')", "path.join(root,'tmp/erd-qa')");
check = check.replace("const parser=require('../node_modules/next/dist/compiled/babel/parser.js');parser.parse", "const parserFile=process.env.ERD_JSX_PARSER||path.resolve(root,'../System/node_modules/next/dist/compiled/babel/parser.js');if(fs.existsSync(parserFile))require(parserFile).parse");
assert(!check.includes('tmp/pdfs/erd-update'));
fs.writeFileSync(path.join(destination, 'check.cjs'), check);
for (const name of ['check-a4.cjs', 'check-print.cjs']) fs.writeFileSync(path.join(destination, name), "// Compatibility entry point: the canonical checker covers all A4 variants.\nrequire('./check.cjs');\n");
console.log('Prepared reproducible ERD builder and canonical checkers.');
